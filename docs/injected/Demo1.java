public class Demo1 {
    /**
     * Adds three integers together, subtracting the third from the sum of the first two.
     *
     * Args:
     *     a (int): The first integer to add.
     *     b (int): The second integer to add.
     *     c (int): The integer to subtract from the sum of a and b.
     *
     * Returns:
     *     int: The result of the addition and subtraction operation.
     */
    public int add(int a, int b,int c) {
        return a + b - c;
    }
} 
